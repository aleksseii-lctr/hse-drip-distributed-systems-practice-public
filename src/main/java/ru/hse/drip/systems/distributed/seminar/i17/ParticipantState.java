package ru.hse.drip.systems.distributed.seminar.i17;

public enum ParticipantState {
    /**
     * Смысл: участник ещё не обещал коммит и ещё не принял финальное решение.
     * Где возникает: до первого onPrepare(txId, op).
     * В INIT у участника нет “обязательств” перед транзакцией.
     */
    INIT,

    /**
     * Смысл: участник проголосовал COMMIT и зафиксировал обещание в WAL, но ещё не знает глобальное решение.
     * Это ключевой смысл 2PC: “я готов коммитить и не могу самовольно передумать”.
     * PREPARED = “я уже пообещал, теперь жду приказа”.
     */
    PREPARED,   // "in doubt"

    /**
     * Смысл: участник применил изменения (локальный commit завершён) и записал это в WAL.
     * Где возникает: после onCommit(txId).
     * COMMITTED — финальное состояние: “это уже часть истины в данных”.
     */
    COMMITTED,

    /**
     * Смысл: участник откатил/освободил ресурсы (или изначально отказал в prepare) и записал это в WAL.
     */
    ABORTED
}
